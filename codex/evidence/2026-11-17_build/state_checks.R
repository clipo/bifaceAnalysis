shiny::testServer(shiny::shinyAppDir(APP_DIR), {
  do.call(session$setInputs,defaults); session$elapse(300)
  p<-processed()
  for(n in 1:4) {
    rv$specimens[[paste0("copy",n)]]<-new_specimen(paste0("copy",n),paste0("copy",n),"",p$std$outline,p$std$base_row)
    statuses<-sapply(figures,function(f)tryCatch({ggplot2::ggplot_build(f());"plot"},error=function(e)if(inherits(e,"shiny.silent.error"))"message"else paste("ERROR",conditionMessage(e))))
    tx<-sapply(texts,function(f)tryCatch({f();"text"},error=function(e)if(inherits(e,"shiny.silent.error"))"message"else paste("ERROR",conditionMessage(e))))
    cat("Identical shapes n",n,"figure statuses",paste(names(statuses),statuses,collapse="; "),"\n")
    cat("Identical shapes n",n,"text statuses",paste(names(tx),tx,collapse="; "),"\n")
    if(n>=3) cat("Identical shapes n",n,"PCA rank",pca()$rank,"max coefficient row difference",max(abs(sweep(coefs(),2,coefs()[1,]))),"retained variance",sum(pca()$sdev^2),"morphospace message",tryCatch({figures$morpho();"plot"},error=function(e)conditionMessage(e)),"\n")
  }
})
